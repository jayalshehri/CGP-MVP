import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
const exports={};vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/assessment.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports});
const {assessmentMetrics:m}=exports;
const row=(status,extra={})=>({is_scoring:true,compliance_status:status,review_status:'accepted',notes:'reason',...extra});
assert.equal(m([],false).compliance,null);
assert.equal(m([row('implemented'),row(null)],true).compliance,50,'unassessed must remain in denominator');
assert.equal(m([row('implemented'),row('not_applicable')],true).compliance,100);
assert.equal(m([row('not_applicable')],true).compliance,null,'all N/A must not show 0');
assert.equal(m([row('implemented')],false).compliance,null,'draft must not appear approved');
assert.equal(m([row('implemented',{review_status:'pending'}),row(null)],true).compliance,0);
assert.equal(m([row('implemented'),row('not_applicable',{review_status:'pending'})],true).compliance,50,'unapproved N/A must not disappear');
assert.equal(m([row('implemented'),row('partially_implemented')],true).compliance,50);
assert.equal(m([row(null,{is_scoring:false}),row('implemented')],true).total,1);
assert.equal(m([row('not_implemented')],false).missing,1);
assert.equal(m([row('not_implemented',{owner_id:'owner',corrective_action:'fix',expected_compliance_date:'2027-01-01'})],false).missing,0);
assert.ok(Math.abs(m([row('implemented'),row(null),row(null)],true).compliance-100/3)<1e-12,'round only at display');
console.log('PASS: 12 assessment denominator, applicability, approval, hierarchy and completeness assertions');
